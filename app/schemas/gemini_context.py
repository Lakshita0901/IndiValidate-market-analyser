"""
app.schemas.gemini_context
--------------------------
Schema definition for Gemini-generated startup context, pain-point hypotheses,
assumptions, and persona-generation guidance.

EPISTEMIC BOUNDARY:
This data represents model-generated hypotheses ONLY.
It must never be inserted into the empirical evidence pool (normalized_evidence,
cleaned_evidence, retrieval_documents, or ChromaDB), and must never receive
empirical evidence labels (such as 'SUPPORTED' / 'Corroborated by Evidence').
"""

from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field


class GeminiFallbackContext(BaseModel):
    """
    Structured startup context and hypotheses generated by Gemini when
    empirical research evidence is absent or insufficient.
    """
    model_config = ConfigDict(extra="ignore")

    market_overview: str = Field(
        description="General overview of the customer ecosystem and market context"
    )
    target_customer_profiles: List[str] = Field(
        default_factory=list,
        description="Plausible customer roles, demographics, or organizational archetypes"
    )
    pain_point_hypotheses: List[str] = Field(
        default_factory=list,
        description="Hypothesized core customer frustrations, workflow bottlenecks, and unmet needs"
    )
    adoption_barrier_hypotheses: List[str] = Field(
        default_factory=list,
        description="Hypothesized switching costs, budget limitations, habit inertia, and operational risks"
    )
    explicit_assumptions: List[str] = Field(
        default_factory=list,
        description="Explicit model assumptions requiring real-world primary validation"
    )
    persona_generation_guidance: List[str] = Field(
        default_factory=list,
        description="Actionable guidance for Mistral to ensure realistic, diverse customer personas"
    )
    provider: str = Field(
        default="google_gemini",
        description="Model provider that generated this context"
    )
    is_empirical_evidence: bool = Field(
        default=False,
        description="Strictly False: model-generated hypothesis context is not empirical evidence"
    )
